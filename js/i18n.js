  function localizeAttributes(element) {
    const attributes = ['aria-label', 'aria-valuetext', 'title', 'placeholder', 'alt'];
    if (element.tagName === 'META') attributes.push('content');
    let originals = originalAttributes.get(element);
    let rendered = renderedAttributes.get(element);
    if (!originals) {
      originals = {};
      rendered = {};
      originalAttributes.set(element, originals);
      renderedAttributes.set(element, rendered);
    }

    attributes.forEach(name => {
      if (!element.hasAttribute(name)) return;
      const current = element.getAttribute(name) || '';
      if (!(name in originals) || (name in rendered && current !== rendered[name])) {
        originals[name] = sourceValue(current);
      }
      const next = language === 'ru' ? originals[name] : translateValue(originals[name]);
      rendered[name] = next;
      if (current !== next) element.setAttribute(name, next);
    });
  }

  function localizeLink(element) {
    if (element.tagName !== 'A' || !element.hasAttribute('href')) return;
    const href = element.getAttribute('href');
    const next = routeHref(href);
    if (href !== next) element.setAttribute('href', next);
  }

  function localizeTree(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      localizeTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) {
      localizeAttributes(root);
      localizeLink(root);
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node);
      else {
        localizeAttributes(node);
        localizeLink(node);
      }
      node = walker.nextNode();
    }
  }

